/// Availability state of the on-device Gemini Nano 4 model via AICore.
enum NanoStatus { available, downloadable, downloading, unavailable }

/// Execution source returned by `firebase-ai` hybrid inference.
enum NanoInferenceSource { onDevice, inCloud }

/// Download progress event emitted by `navisense/gemini_nano/download`.
@immutable
final class NanoDownloadProgress {
  /// Creates a [NanoDownloadProgress].
  const NanoDownloadProgress({
    required this.state,
    required this.bytesDownloaded,
    required this.totalBytes,
  });

  /// Status string (`DOWNLOADING` or `COMPLETED`).
  final String state;

  /// Cumulative bytes downloaded so far.
  final int bytesDownloaded;

  /// Total bytes reported by AICore (may be `0` if unknown).
  final int totalBytes;

  /// Progress in `[0.0, 1.0]`, or `null` when [totalBytes] is unavailable.
  double? get progress01 =>
      totalBytes > 0 ? (bytesDownloaded / totalBytes).clamp(0.0, 1.0) : null;

  /// Integer percentage `[0, 100]`, or `null` when [totalBytes] is unavailable.
  int? get percent => progress01 == null ? null : (progress01! * 100).round();

  /// Whether AICore signaled download completion.
  bool get isCompleted => state == 'COMPLETED';

  @override
  bool operator ==(Object other) =>
      identical(this, other) ||
      other is NanoDownloadProgress &&
          runtimeType == other.runtimeType &&
          state == other.state &&
          bytesDownloaded == other.bytesDownloaded &&
          totalBytes == other.totalBytes;

  @override
  int get hashCode => Object.hash(state, bytesDownloaded, totalBytes);
}

/// Typed result returned by [NanoBridge.generate].
@immutable
final class NanoResult {
  /// Creates a [NanoResult].
  const NanoResult({
    required this.text,
    required this.inferenceSource,
    required this.latencyMs,
  });

  /// Spoken guidance text generated by the hybrid model.
  final String text;

  /// Actual inference execution location (`ON_DEVICE` or `IN_CLOUD`).
  final NanoInferenceSource inferenceSource;

  /// Measured native round-trip duration in milliseconds.
  final int latencyMs;

  @override
  bool operator ==(Object other) =>
      identical(this, other) ||
      other is NanoResult &&
          runtimeType == other.runtimeType &&
          text == other.text &&
          inferenceSource == other.inferenceSource &&
          latencyMs == other.latencyMs;

  @override
  int get hashCode => Object.hash(text, inferenceSource, latencyMs);
}

/// Abstracts [NanoBridge] operations for orchestrator and UI testing.
abstract interface class NanoBridgeClient {
  /// Queries current Gemini Nano 4 availability on this Android device.
  Future<NanoStatus> getStatus();

  /// Starts downloading Gemini Nano 4 via AICore.
  Future<void> startDownload();

  /// Emits download progress events from `navisense/gemini_nano/download`.
  Stream<NanoDownloadProgress> get downloadProgress;

  /// Runs multimodal spatial reasoning on [jpeg] and Stage 0 [summary].
  Future<NanoResult> generate({
    required Uint8List jpeg,
    required String summary,
    String systemInstruction,
  });
}

/// Provides the production [NanoBridgeClient].
final nanoBridgeProvider = Provider<NanoBridgeClient>((ref) => NanoBridge());

/// Streams Gemini Nano 4 download progress from the native bridge.
final nanoDownloadProgressProvider = StreamProvider<NanoDownloadProgress>((
  ref,
) {
  return ref.watch(nanoBridgeProvider).downloadProgress;
});

/// Reactive Gemini Nano 4 availability status; refreshes on resume and
/// automatically flips to [NanoStatus.available] after download completes.
final nanoStatusProvider =
    AsyncNotifierProvider<NanoStatusNotifier, NanoStatus>(
  NanoStatusNotifier.new,
);

/// Manages lifecycle-aware Gemini Nano status checks.
final class NanoStatusNotifier extends AsyncNotifier<NanoStatus>
    with WidgetsBindingObserver {
  bool _observerRegistered = false;

  @override
  Future<NanoStatus> build() async {
    if (!_observerRegistered) {
      WidgetsBinding.instance.addObserver(this);
      _observerRegistered = true;
    }

    ref.onDispose(() {
      if (_observerRegistered) {
        WidgetsBinding.instance.removeObserver(this);
        _observerRegistered = false;
      }
    });

    ref.listen<AsyncValue<NanoDownloadProgress>>(nanoDownloadProgressProvider, (
      AsyncValue<NanoDownloadProgress>? previous,
      AsyncValue<NanoDownloadProgress> next,
    ) {
      final progress = next.value;
      if (progress != null && progress.isCompleted) {
        unawaited(refresh());
      }
    });

    return ref.read(nanoBridgeProvider).getStatus();
  }

  /// Re-queries Gemini Nano availability (for example after resume or eviction).
  Future<void> refresh() async {
    final nextStatus = await AsyncValue.guard(
      () => ref.read(nanoBridgeProvider).getStatus(),
    );
    if (!ref.mounted) return;
    state = nextStatus;
  }

  @override
  void didChangeAppLifecycleState(AppLifecycleState state) {
    if (state == AppLifecycleState.resumed && ref.mounted) {
      unawaited(refresh());
    }
  }
}

/// Typed Dart client for the `navisense/gemini_nano` Android bridge.
final class NanoBridge implements NanoBridgeClient {
  /// Creates a [NanoBridge].
  NanoBridge({
    MethodChannel? methodChannel,
    EventChannel? downloadChannel,
    Duration generateTimeout = const Duration(milliseconds: 9000),
  })  : _methodChannel = methodChannel ?? _defaultMethodChannel,
        _downloadChannel = downloadChannel ?? _defaultDownloadChannel,
        _generateTimeout = generateTimeout;

  /// MethodChannel name shared with `GeminiNanoBridge.kt`.
  static const String methodChannelName = 'navisense/gemini_nano';

  /// EventChannel name for Gemini Nano download progress.
  static const String downloadChannelName = 'navisense/gemini_nano/download';

  /// Default Tier 1 system instruction matching `2-architecture.md` §2.4.
  static const String defaultSystemInstruction =
      'You are NaviSense, a calm spatial guide for a blind pedestrian. '
      'Reply in ONE or TWO short sentences. Mention the closest hazard first with its direction '
      '(left, ahead, right) and distance (very close, a few steps, far). Read important signs. '
      'Never describe colors or aesthetics unless safety-relevant. Never speculate.';

  static const MethodChannel _defaultMethodChannel = MethodChannel(
    methodChannelName,
  );
  static const EventChannel _defaultDownloadChannel = EventChannel(
    downloadChannelName,
  );

  final MethodChannel _methodChannel;
  final EventChannel _downloadChannel;
  final Duration _generateTimeout;

  @override
  Future<NanoStatus> getStatus() async {
    try {
      final raw = await _methodChannel.invokeMethod<String>('getStatus');
      return parseStatus(raw);
    } on PlatformException catch (e, st) {
      log(
        'Nano getStatus returned error; treating as unavailable',
        name: 'navisense.nano',
        error: e,
        stackTrace: st,
      );
      return NanoStatus.unavailable;
    } on MissingPluginException {
      return NanoStatus.unavailable;
    }
  }

  /// Parses raw status string from `GeminiNanoBridge.kt`.
  static NanoStatus parseStatus(String? raw) => switch (raw) {
        'AVAILABLE' => NanoStatus.available,
        'DOWNLOADABLE' => NanoStatus.downloadable,
        'DOWNLOADING' => NanoStatus.downloading,
        _ => NanoStatus.unavailable,
      };

  @override
  Future<void> startDownload() async {
    try {
      await _methodChannel.invokeMethod<void>('startDownload');
    } on PlatformException catch (e) {
      throw NanoFailure(
        e.message ?? 'Failed to start Gemini Nano download',
        code: e.code,
      );
    } on MissingPluginException {
      throw const NanoFailure(
        'Gemini Nano bridge is unavailable on this host',
        code: 'NANO_UNAVAILABLE',
      );
    }
  }

  @override
  Stream<NanoDownloadProgress> get downloadProgress {
    return _downloadChannel.receiveBroadcastStream().map((Object? event) {
      if (event is! Map<Object?, Object?>) {
        throw const NanoFailure(
          'Malformed download progress payload',
          code: 'NANO_FAILED',
        );
      }
      final state = event['state'];
      final bytesDownloaded = event['bytesDownloaded'];
      final totalBytes = event['totalBytes'];
      if (state is! String || bytesDownloaded is! int || totalBytes is! int) {
        throw const NanoFailure(
          'Malformed download progress fields',
          code: 'NANO_FAILED',
        );
      }
      return NanoDownloadProgress(
        state: state,
        bytesDownloaded: bytesDownloaded,
        totalBytes: totalBytes,
      );
    }).handleError((Object error) {
      if (error is PlatformException) {
        throw NanoFailure(
          error.message ?? 'Gemini Nano download failed',
          code: error.code,
        );
      }
      if (error is NaviFailure) throw error;
      throw NanoFailure(error.toString(), code: 'NANO_FAILED');
    });
  }

  @override
  Future<NanoResult> generate({
    required Uint8List jpeg,
    required String summary,
    String systemInstruction = defaultSystemInstruction,
  }) async {
    try {
      final raw = await _methodChannel
          .invokeMethod<Object?>('generate', <String, Object?>{
        'jpeg': jpeg,
        'summary': summary,
        'systemInstruction': systemInstruction,
      }).timeout(_generateTimeout);

      return _parseGenerateResult(raw);
    } on TimeoutException {
      throw const TimeoutFailure('Nano bridge exceeded 9000ms');
    } on PlatformException catch (e) {
      throw NanoFailure(
        e.message ?? 'Gemini Nano inference failed',
        code: e.code,
      );
    } on MissingPluginException {
      throw const NanoFailure(
        'Gemini Nano bridge is unavailable on this host',
        code: 'NANO_UNAVAILABLE',
      );
    }
  }

  static NanoResult _parseGenerateResult(Object? raw) {
    if (raw is! Map<Object?, Object?>) {
      throw const NanoFailure(
        'Malformed response from Gemini Nano bridge',
        code: 'NANO_FAILED',
      );
    }
    final text = raw['text'];
    final sourceRaw = raw['inferenceSource'];
    final latencyMs = raw['latencyMs'];
    if (text is! String ||
        text.trim().isEmpty ||
        sourceRaw is! String ||
        latencyMs is! int) {
      throw const NanoFailure(
        'Malformed response fields from Gemini Nano bridge',
        code: 'NANO_FAILED',
      );
    }

    final inferenceSource = switch (sourceRaw) {
      'ON_DEVICE' => NanoInferenceSource.onDevice,
      'IN_CLOUD' => NanoInferenceSource.inCloud,
      _ => throw const NanoFailure(
          'Unknown inferenceSource from Gemini Nano bridge',
          code: 'NANO_FAILED',
        ),
    };

    return NanoResult(
      text: text.trim(),
      inferenceSource: inferenceSource,
      latencyMs: latencyMs,
    );
  }
}
